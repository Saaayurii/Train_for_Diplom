const alphabet = 'АБВГДЕЖЗИКЛМНОПРСТУФХЦЧШЩЭЮЯ'.split('');

const categoryColor: Record<Category, string> = {
  Инфраструктура: 'cat--infra',
  'Подвижной состав': 'cat--rolling',
  Управление: 'cat--mgmt',
  Сигнализация: 'cat--signal',
};

function getFirstLetter(term: string) {
  return term.charAt(0).toUpperCase();
}

export default function GlossaryPage() {
  const [search, setSearch] = useState('');
  const letterRefs = useRef<Record<string, HTMLDivElement | null>>({});
  const [currentImageIndex, setCurrentImageIndex] = useState(0);

  useEffect(() => {
    const interval = setInterval(() => {
      setCurrentImageIndex((prev) => (prev + 1) % trainImages.length);
    }, 5000);
    return () => clearInterval(interval);
  }, []);

  const filtered = terms.filter(
    (t) =>
      t.term.toLowerCase().includes(search.toLowerCase()) ||
      t.definition.toLowerCase().includes(search.toLowerCase()),
  );

  const grouped = filtered.reduce<Record<string, GlossaryTerm[]>>((acc, term) => {
    const letter = getFirstLetter(term.term);
    if (!acc[letter]) acc[letter] = [];
    acc[letter].push(term);
    return acc;
  }, {});

  const availableLetters = new Set(Object.keys(grouped));

  const scrollToLetter = useCallback((letter: string) => {
    const el = letterRefs.current[letter];
    if (el) {
      el.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
  }, []);

  return (
    <ModalProvider>
      <NavBar />
      <div className="glossary-page">
        <div className="glossary-hero">
          <div className="hero-background">
            {trainImages.map((img, index) => (
              <div key={img} className={`hero-image ${index === currentImageIndex ? 'active' : ''}`}>
                <ImageWithFallback src={img} alt={`Поезд ${index + 1}`} showPlaceholder={false} />
              </div>
            ))}
            <div className="hero-overlay" />
          </div>
          <div className="glossary-hero__content">
            <h1 className="glossary-hero__title">Глоссарий</h1>
            <p className="glossary-hero__subtitle">Словарь железнодорожных терминов и определений</p>
          </div>
        </div>

        <div className="glossary-container">
          <div className="glossary-search-bar">
            <div className="glossary-search-wrap">
              <span className="glossary-search-icon">🔍</span>
              <input
                type="text"
                className="glossary-search-input"
                placeholder="Поиск по терминам и определениям..."
                value={search}
                onChange={(e) => setSearch(e.target.value)}
              />
              {search && (
                <button
                  type="button"
                  className="glossary-search-clear"
                  onClick={() => setSearch('')}
                  aria-label="Очистить"
                >
                  ✕
                </button>
              )}
            </div>
            <div className="glossary-count">
              {filtered.length === terms.length
                ? `${terms.length} терминов`
                : `Найдено: ${filtered.length} из ${terms.length}`}
            </div>
          </div>

          <div className="glossary-alphabet">
            {alphabet.map((letter) => (
              <button
                key={letter}
                type="button"
                className={`alpha-btn ${availableLetters.has(letter) ? 'alpha-btn--active' : 'alpha-btn--disabled'}`}
                onClick={() => availableLetters.has(letter) && scrollToLetter(letter)}
                disabled={!availableLetters.has(letter)}
              >
                {letter}
              </button>
            ))}
          </div>

          <div className="glossary-body">
            {Object.keys(grouped)
              .sort()
              .map((letter) => (
                <div
                  key={letter}
                  className="glossary-letter-group"
                  ref={(el) => {
                    letterRefs.current[letter] = el;
                  }}
                >
                  <div className="glossary-letter-heading">{letter}</div>
                  <div className="glossary-terms-list">
                    {grouped[letter].map((item) => (
                      <div key={item.term} className="glossary-term-card">
                        <div className="glossary-term-card__header">
                          <h3 className="glossary-term-card__name">{item.term}</h3>
                          <span className={`glossary-category ${categoryColor[item.category]}`}>
                            {item.category}
                          </span>
                        </div>
                        <p className="glossary-term-card__definition">{item.definition}</p>
                      </div>
                    ))}
                  </div>
                </div>
              ))}

            {filtered.length === 0 && (
              <div className="glossary-empty">
                <span className="glossary-empty__icon">🔍</span>
                <p>По запросу «{search}» ничего не найдено</p>
              </div>
            )}
          </div>
        </div>
      </div>
    </ModalProvider>
  );
}
